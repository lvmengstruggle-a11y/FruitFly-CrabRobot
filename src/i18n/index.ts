export function translate(locale: Locale, key: string, vars?: Record<string, string | number>) {
  const table = messages[locale] as Record<string, string>;
  const raw = table[key] ?? (messages.en as Record<string, string>)[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => vars[name] == null ? '' : String(vars[name]));
}

function readStored(): Locale | undefined {
  try {
    const saved = globalThis.localStorage?.getItem(STORAGE_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
  } catch { /* private mode */ }
  return undefined;
}

function readQuery(): Locale | undefined {
  const value = new URLSearchParams(globalThis.location?.search ?? '').get('lang');
  return value === 'zh' || value === 'en' ? value : undefined;
}

function detect(): Locale {
  const stored = readStored();
  if (stored) return stored;
  const query = readQuery();
  if (query) return query;
  return (globalThis.navigator?.language ?? '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

class I18n {
  locale: Locale = detect();
  set(locale: Locale) {
    this.locale = locale;
    try { globalThis.localStorage?.setItem(STORAGE_KEY, locale); } catch { /* private mode */ }
  }
  t(key: string, vars?: Record<string, string | number>) { return translate(this.locale, key, vars); }
}

export const i18n = new I18n();
export const t = (key: string, vars?: Record<string, string | number>) => i18n.t(key, vars);
